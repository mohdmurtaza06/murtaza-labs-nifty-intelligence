@app.post("/api/run-pipeline")
def run_pipeline():

    if pipeline_status["running"]:

        return {

            "status":
                "already_running",

            "message":
                "Daily pipeline is already running."
        }

    acquired = (
        pipeline_lock.acquire(
            blocking=False
        )
    )

    if not acquired:

        return {

            "status":
                "already_running",

            "message":
                "Daily pipeline is already running."
        }

    thread = threading.Thread(

        target=run_pipeline_background,

        kwargs={
            "source": "manual"
        },

        daemon=True
    )

    thread.start()

    return {

        "status":
            "started",

        "message":
            "Daily pipeline started."
    }


