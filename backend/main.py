@app.post("/api/run-pipeline")
def run_pipeline(request: Request):
    # This endpoint launches a resource-consuming subprocess. CORS does not
    # authenticate callers, so require a server-side token and a matching
    # request header. If no token is configured, the manual endpoint stays
    # disabled; the internal scheduled job remains separate.
    configured_token = os.environ.get("PIPELINE_TRIGGER_TOKEN", "").strip()
    if not configured_token:
        raise HTTPException(
            status_code=503,
            detail=(
                "Manual pipeline triggering is disabled. Configure "
                "PIPELINE_TRIGGER_TOKEN on the backend to enable it."
            ),
        )

    supplied_token = request.headers.get("X-Pipeline-Token", "")
    if not hmac.compare_digest(supplied_token, configured_token):
        raise HTTPException(
            status_code=403,
            detail="Missing or invalid pipeline trigger token.",
        )

    if pipeline_status["running"]:

        return {

            "status":
                "already_running",

            "message":
                "Daily pipeline is already running."
        }

    acquired = (
        pipeline_lock.acquire(
            blocking=False
        )
    )

    if not acquired:

        return {

            "status":
                "already_running",

            "message":
                "Daily pipeline is already running."
        }

    thread = threading.Thread(

        target=run_pipeline_background,

        kwargs={
            "source": "manual"
        },

        daemon=True
    )

    thread.start()

    return {

        "status":
            "started",

        "message":
            "Daily pipeline started."
    }


# ============================================================
# AUTOMATIC PIPELINE
# ============================================================

def start_automatic_pipeline():

    global last_automatic_trigger_date

    today = datetime.now(
        IST
    ).date()

    # --------------------------------------------------------
    # Weekend protection
    # --------------------------------------------------------

    if today.weekday() >= 5:

        print(
            "Automatic pipeline skipped: "
            "weekend."
        )

        return

    # --------------------------------------------------------
    # Prevent duplicate trigger during the same scheduler
    # window.
    # --------------------------------------------------------

    if (
        last_automatic_trigger_date
        == today
    ):

        return

    # --------------------------------------------------------
    # Prevent duplicate execution if today's pipeline already
    # completed.
    # --------------------------------------------------------

    last_run = (
        get_last_pipeline_date()
    )

    if last_run == today:

        print(
            "Automatic pipeline skipped: "
            "already completed today."
        )

        last_automatic_trigger_date = (
            today
        )

        return

    # --------------------------------------------------------
    # Prevent concurrent execution.
    # --------------------------------------------------------

    if pipeline_status["running"]:

        print(
            "Automatic pipeline skipped: "
            "pipeline already running."
        )

        return

    acquired = (
        pipeline_lock.acquire(
            blocking=False
        )
    )

    if not acquired:

        print(
            "Automatic pipeline skipped: "
            "pipeline lock is active."
        )

        return

    # Mark the trigger immediately so the scheduler
    # cannot trigger the same automatic job again.
    last_automatic_trigger_date = today

    print()
    print("=" * 70)
    print(
        "AUTOMATIC DAILY PIPELINE TRIGGERED"
    )
    print("=" * 70)

    thread = threading.Thread(

        target=run_pipeline_background,

        kwargs={
            "source": "automatic"
        },

        daemon=True
    )

    thread.start()


# ============================================================
# AUTOMATIC SCHEDULER
# ============================================================

def automatic_pipeline_scheduler():

    """
    Runs continuously in a background thread.

    Schedule:
        Monday-Friday
        16:00 IST

    The scheduler checks every 20 seconds.
    """

    scheduled_hour = 16
    scheduled_minute = 0

    print()
    print(
        "Automatic scheduler started."
    )

    while True:

        try:

            now = datetime.now(
                IST
            )

            # ------------------------------------------------
            # Monday-Friday
            # ------------------------------------------------

            if now.weekday() < 5:

                scheduled_time = time(
                    scheduled_hour,
                    scheduled_minute
                )

                current_time = now.time()

                window_start = (
                    scheduled_time
                )

                window_end = (
                    datetime.combine(
                        now.date(),
                        scheduled_time
                    )
                    + timedelta(
                        minutes=10
                    )
                ).time()

                # ------------------------------------------------
                # Trigger during the 16:00-16:10 window.
                # ------------------------------------------------

                if (
                    current_time >= window_start
                    and
                    current_time < window_end
                ):

                    start_automatic_pipeline()

            # ------------------------------------------------
            # Check every 20 seconds.
            # ------------------------------------------------

            time_module.sleep(
                20
            )

        except Exception as e:

            print(
                "Scheduler error:",
                e
            )

            time_module.sleep(
                30
            )