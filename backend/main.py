RUN_MARKER = DATA_DIR / ".last_pipeline_run"


def get_last_pipeline_date():
    """
    Return the date on which the pipeline last completed
    successfully.
    """

    if not RUN_MARKER.exists():
        return None

    try:
        value = RUN_MARKER.read_text(
            encoding="utf-8"
        ).strip()

        if not value:
            return None

        return datetime.strptime(
            value,
            "%Y-%m-%d"
        ).date()

    except Exception:
        return None


def mark_pipeline_complete():
    """
    Record today's date after a successful pipeline.
    """

    DATA_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    today = datetime.now(
        IST
    ).date()

    RUN_MARKER.write_text(
        today.strftime("%Y-%m-%d"),
        encoding="utf-8"
    )


