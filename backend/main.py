def automatic_pipeline_scheduler():

    """
    Runs continuously in a background thread.

    Schedule:
        Monday-Friday
        15:45 IST

    The scheduler checks every 20 seconds.
    """

    scheduled_hour = 15
    scheduled_minute = 45

    print()
    print(
        "Automatic scheduler started."
    )

    while True:

        try:

            now = datetime.now(
                IST
            )

            # ------------------------------------------------
            # Monday-Friday
            # ------------------------------------------------

            if now.weekday() < 5:

                scheduled_time = time(
                    scheduled_hour,
                    scheduled_minute
                )

                current_time = now.time()

                window_start = (
                    scheduled_time
                )

                window_end = (
                    datetime.combine(
                        now.date(),
                        scheduled_time
                    )
                    + timedelta(
                        minutes=5
                    )
                ).time()

                # ------------------------------------------------
                # Trigger during the 15:45-15:50 window.
                # ------------------------------------------------

                if (
                    current_time >= window_start
                    and
                    current_time < window_end
                ):

                    start_automatic_pipeline()

            # ------------------------------------------------
            # Check every 20 seconds.
            # ------------------------------------------------

            time_module.sleep(
                20
            )

        except Exception as e:

            print(
                "Scheduler error:",
                e
            )

            time_module.sleep(
                30
            )