def get_research_prediction_data():
    """
    Read the prediction generated by:
        notebooks/15_live_prediction_production.py

    This is a validated, fresh research candidate signal only. It is not an
    approved production model and must never authorize live execution.
    """

    if not RESEARCH_PREDICTION_FILE.exists():
        return None

    try:
        with open(
            RESEARCH_PREDICTION_FILE,
            "r",
            encoding="utf-8",
        ) as f:
            data = json.load(f)

        if not isinstance(data, dict):
            return None

        # This project currently serves research candidate signals only.
        # Do not imply production approval or accept old target conventions.
        if data.get("trading_mode") != "RESEARCH_ONLY":
            raise ValueError("Prediction artifact is not marked research-only.")
        if data.get("production_eligible") is not False:
            raise ValueError("Research artifact must explicitly remain production-ineligible.")
        if data.get("live_orders_enabled") is not False:
            raise ValueError("Live orders must be explicitly disabled.")
        expected_target = "next_session_open_to_close_direction"
        if data.get("target_horizon") != expected_target:
            raise ValueError(
                "Prediction uses an outdated or unsupported target horizon."
            )
        prediction_date = str(data.get("prediction_date", ""))[:10]
        market_data_date = str(
            data.get("market_data_date") or data.get("prediction_date", "")
        )[:10]
        if not prediction_date or prediction_date != market_data_date:
            raise ValueError("Prediction date and market-data date do not match.")

        # Never serve a saved artifact as current when its market observation
        # is stale, future-dated, or its probabilities are invalid.
        validate_market_data_freshness(
            market_data_date,
            max_age_days=4,
            require_latest_completed_session=True,
        )
        probability_up, probability_down = validate_probability_pair(
            data.get("probability_up"),
            data.get("probability_down"),
        )
        prediction = str(data.get("prediction", "")).upper()
        expected_prediction = "UP" if probability_up >= probability_down else "DOWN"
        if prediction != expected_prediction:
            raise ValueError("Prediction label disagrees with its probabilities.")

        confidence = float(data.get("confidence"))
        if not 0 <= confidence <= 1 or abs(
            confidence - max(probability_up, probability_down)
        ) > 0.002:
            raise ValueError("Prediction confidence is invalid or inconsistent.")

        data["available"] = True
        data["freshness_verified"] = True
        return data

    except Exception as e:
        print(
            "Research prediction read error:",
            str(e),
        )
        return None


