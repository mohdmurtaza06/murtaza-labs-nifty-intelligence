def load_market_dataframe(limit=400):
    """Load chronological market history with enough rows for 200-day indicators."""
    file = DATA_DIR / "live_market_data.csv"
    if not file.exists():
        return pd.DataFrame()

    try:
        df = pd.read_csv(file)
        if df.empty:
            return df

        if "Date" in df.columns:
            parsed_dates = pd.to_datetime(df["Date"], errors="coerce")
            df = df.assign(_parsed_date=parsed_dates)
            df = df.sort_values("_parsed_date", kind="stable")
            df = df.drop(columns=["_parsed_date"])

        return df.tail(limit).reset_index(drop=True)
    except Exception as exc:
        print("Market snapshot error:", str(exc))
        return pd.DataFrame()


def numeric_or_none(value, zero_is_missing=False):
    try:
        if value is None or value == "":
            return None
        number = float(value)
        if pd.isna(number) or not pd.api.types.is_number(number):
            return None
        if zero_is_missing and number <= 0:
            return None
        return number
    except Exception:
        return None


def derive_market_snapshot():
    """Derive trustworthy display-only values from the market history."""
    df = load_market_dataframe(400)
    if df.empty or "Close" not in df.columns:
        return {}

    closes = pd.to_numeric(df["Close"], errors="coerce").dropna()
    snapshot = {}

    if len(closes) >= 2 and float(closes.iloc[-2]) != 0:
        snapshot["day_change_pct"] = (
            (float(closes.iloc[-1]) / float(closes.iloc[-2]) - 1.0) * 100.0
        )

    # India VIX is never a meaningful zero. Treat zero/missing as unavailable.
    for column in ("India_VIX", "India_VIX_Close", "VIX"):
        if column in df.columns:
            series = pd.to_numeric(df[column], errors="coerce").dropna()
            if not series.empty and float(series.iloc[-1]) > 0:
                snapshot["india_vix"] = float(series.iloc[-1])
                break

    return snapshot


