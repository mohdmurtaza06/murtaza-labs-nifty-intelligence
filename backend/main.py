def parse_bool(value):

    if pd.isna(value):
        return None

    if isinstance(value, bool):
        return value

    value = str(value).strip().lower()

    if value in [
        "true",
        "1",
        "yes"
    ]:
        return True

    if value in [
        "false",
        "0",
        "no"
    ]:
        return False

    return None


