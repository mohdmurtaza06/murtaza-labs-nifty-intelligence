def run_pipeline_background(
    source="manual"
):

    try:

        pipeline_status["running"] = True

        pipeline_status["last_started"] = (
            datetime.now(
                IST
            ).isoformat()
        )

        pipeline_status["last_status"] = (
            "running"
        )

        pipeline_status["last_error"] = None

        print()
        print("=" * 70)
        print(
            f"NIFTY PIPELINE STARTED "
            f"({source.upper()})"
        )
        print("=" * 70)

        # ----------------------------------------------------
        # Check that the pipeline exists.
        # ----------------------------------------------------

        if not PIPELINE_SCRIPT.exists():

            raise FileNotFoundError(
                "Pipeline script not found: "
                f"{PIPELINE_SCRIPT}"
            )

        # ----------------------------------------------------
        # UTF-8 ENVIRONMENT FIX
        #
        # This is the important fix.
        #
        # Your 14_live_data.py contains Unicode characters
        # such as:
        #
        #     →
        #
        # Windows CP1252 cannot encode them.
        #
        # These environment variables force the child Python
        # process to use UTF-8.
        # ----------------------------------------------------

        env = os.environ.copy()

        env["PYTHONUNBUFFERED"] = "1"

        env["PYTHONIOENCODING"] = "utf-8"

        env["PYTHONUTF8"] = "1"

        # ----------------------------------------------------
        # Launch the pipeline.
        # ----------------------------------------------------

        result = subprocess.run(

            [
                sys.executable,

                "-X",
                "utf8",

                "-u",

                str(
                    PIPELINE_SCRIPT
                )
            ],

            cwd=str(
                PROJECT_DIR
            ),

            capture_output=True,

            text=True,

            encoding="utf-8",

            errors="replace",

            timeout=600,

            env=env
        )

        stdout = (
            result.stdout
            or ""
        )

        stderr = (
            result.stderr
            or ""
        )

        # ----------------------------------------------------
        # PRINT STDOUT
        # ----------------------------------------------------

        print()
        print("=" * 70)
        print(
            "DAILY PIPELINE STDOUT"
        )
        print("=" * 70)

        if stdout.strip():

            print(
                stdout
            )

        else:

            print(
                "(no stdout)"
            )

        # ----------------------------------------------------
        # PRINT STDERR
        # ----------------------------------------------------

        print()
        print("=" * 70)
        print(
            "DAILY PIPELINE STDERR"
        )
        print("=" * 70)

        if stderr.strip():

            print(
                stderr
            )

        else:

            print(
                "(no stderr)"
            )

        # ----------------------------------------------------
        # EXIT CODE
        # ----------------------------------------------------

        print()
        print(
            f"PIPELINE EXIT CODE: "
            f"{result.returncode}"
        )

        print("=" * 70)

        # ----------------------------------------------------
        # PIPELINE FAILED
        # ----------------------------------------------------

        if result.returncode != 0:

            error_text = (
                stderr.strip()
            )

            if not error_text:

                error_text = (
                    stdout.strip()
                )

            if not error_text:

                error_text = (
                    "Pipeline exited "
                    f"with code "
                    f"{result.returncode}"
                )

            # Keep the most useful portion of the error.
            pipeline_status["last_error"] = (
                error_text[-5000:]
            )

            pipeline_status["last_status"] = (
                "failed"
            )

            print()
            print("=" * 70)
            print(
                "NIFTY PIPELINE FAILED"
            )
            print("=" * 70)

            print(
                pipeline_status[
                    "last_error"
                ]
            )

            print("=" * 70)

            return

        # ----------------------------------------------------
        # PIPELINE SUCCESS
        # ----------------------------------------------------

        mark_pipeline_complete()

        pipeline_status["last_status"] = (
            "completed"
        )

        pipeline_status["last_completed"] = (
            datetime.now(
                IST
            ).isoformat()
        )

        pipeline_status["last_error"] = None

        print()
        print("=" * 70)
        print(
            "NIFTY PIPELINE COMPLETED "
            "SUCCESSFULLY"
        )
        print("=" * 70)

    # --------------------------------------------------------
    # TIMEOUT
    # --------------------------------------------------------

    except subprocess.TimeoutExpired as e:

        pipeline_status["last_status"] = (
            "timeout"
        )

        pipeline_status["last_error"] = (
            "Pipeline exceeded "
            "the 10 minute timeout."
        )

        print()
        print("=" * 70)
        print(
            "NIFTY PIPELINE TIMEOUT"
        )
        print("=" * 70)

        if getattr(
            e,
            "stderr",
            None
        ):

            print(
                e.stderr
            )

    # --------------------------------------------------------
    # OTHER ERROR
    # --------------------------------------------------------

    except Exception as e:

        pipeline_status["last_status"] = (
            "failed"
        )

        pipeline_status["last_error"] = (
            str(e)
        )

        print()
        print("=" * 70)
        print(
            "NIFTY PIPELINE ERROR"
        )
        print("=" * 70)

        print(
            str(e)
        )

        print("=" * 70)

    finally:

        pipeline_status["running"] = False

        # The lock is acquired before this function is started.
        try:

            pipeline_lock.release()

        except RuntimeError:

            pass


